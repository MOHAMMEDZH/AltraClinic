export const PORTAL_MESSAGES: Record<PortalLocale, Record<string, string>> = {
  en: EN,
  ar: AR,
};

export function resolvePortalLocale(candidate?: string | null): PortalLocale {
  const raw = (candidate ?? 'en').trim().toLowerCase();
  if (raw.startsWith('ar')) return 'ar';
  return 'en';
}

export function t(locale: PortalLocale, key: string): string {
  return PORTAL_MESSAGES[locale][key] ?? PORTAL_MESSAGES.en[key] ?? key;
}

/** Simple pluralization helper for count-sensitive UI copy. */
export function tp(locale: PortalLocale, keyOne: string, keyOther: string, count: number): string {
  return t(locale, count === 1 ? keyOne : keyOther);
}

export function formatPortalDate(
  value: Date,
  locale: PortalLocale,
  timeZone?: string,
): string {
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar' : 'en-US', {
    dateStyle: 'medium',
    timeStyle: 'short',
    timeZone,
  }).format(value);
}

export function formatPortalNumber(value: number, locale: PortalLocale): string {
  return new Intl.NumberFormat(locale === 'ar' ? 'ar' : 'en-US').format(value);
}
